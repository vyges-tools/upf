//! `vyges_upf` — power intent (UPF) for designs with several power domains: domains, isolation,
//! level shifters, power switches.
//!
//! Stages are added here one at a time, each named after the step it performs and kept in the order
//! the command runs them.
//!
//! The intent is held as plain data ([`PowerIntent`]) so the writer is a pure function of it: the
//! database read lives in [`odb`], behind the `odb` feature, and nothing here needs a database to
//! be tested.

// The crate's own name inside it: the command-line entry ([`cli_main`]) is built into the
// library too, and its `vyges_upf::…` paths resolve here.
extern crate self as vyges_upf;

#[cfg(feature = "odb")]
pub mod odb;

/// `run`: a UPF file read into the database, through the reference's three layers.
pub mod read;
/// `eval`: the power intent made physical (regions, groups, hierarchy), as the floorplan does it.
pub mod eval;
/// The Tcl a UPF file is written in, and the shared argument parsing.
pub mod tcl;

/// The power intent of one block, each list in the database's own order.
///
/// 🔑 **Order is output.** The writer walks each list as given, and the database keeps every one of
/// these tables in creation order — the order the UPF declared them in, not name order.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct PowerIntent {
    pub domains: Vec<Domain>,
    pub ports: Vec<LogicPort>,
    pub switches: Vec<PowerSwitch>,
    pub isolations: Vec<Isolation>,
    pub level_shifters: Vec<LevelShifter>,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct Domain {
    pub name: String,
    /// Set when the floorplan evaluates the intent, NOT by reading it: a freshly read top domain
    /// carries `.` as an ordinary element instead.
    pub top: bool,
    pub elements: Vec<String>,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct LogicPort {
    pub name: String,
    pub direction: String,
}

/// `(port, supply net)`; the net may be empty.
pub type SupplyPort = (String, String);

#[derive(Debug, Clone, Default, PartialEq)]
pub struct PowerSwitch {
    pub name: String,
    /// `(port, supply net)`; an empty port means none was given.
    pub output: SupplyPort,
    pub inputs: Vec<SupplyPort>,
    /// `(port, net)`.
    pub controls: Vec<(String, String)>,
    /// `(state, input supply port, boolean expression)`.
    pub on_states: Vec<(String, String, String)>,
    /// `(port, net, boolean expression)`.
    pub acks: Vec<(String, String, String)>,
    pub domain: String,
    /// The mapped library cell, if `map_power_switch` gave one.
    pub lib_cell: Option<String>,
    /// `(model port, cell terminal)`, by model port.
    pub port_map: Vec<(String, String)>,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct Isolation {
    pub name: String,
    pub domain: String,
    pub applies_to: String,
    pub location: String,
    pub clamp_value: String,
    pub isolation_signal: String,
    pub isolation_sense: String,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct LevelShifter {
    pub name: String,
    pub domain: String,
    pub elements: Vec<String>,
    pub exclude_elements: Vec<String>,
    pub source: String,
    pub sink: String,
    pub use_functional_equivalence: bool,
    pub applies_to: String,
    pub applies_to_boundary: String,
    pub rule: String,
    /// ⚠️ `f32` as the database stores it: widening first would print a different third decimal.
    pub threshold: f32,
    pub no_shift: bool,
    pub force_shift: bool,
    pub location: String,
    pub input_supply: String,
    pub output_supply: String,
    pub internal_supply: String,
    pub name_prefix: String,
    pub name_suffix: String,
    /// `(instance, port)`.
    pub instances: Vec<(String, String)>,
}

/// The first line of every file written. It names the writing tool, so a scorer compares from the
/// second line on.
pub const HEADER: &str = "# UPF generated by Vyges";

/// `write`: the intent as UPF text.
///
/// The sequence is the whole of it — a header, then five sections, each a banner and one command
/// per object, always all five even when a section is empty.
pub fn write_upf(pi: &PowerIntent) -> String {
    let mut o = String::new();
    write_header(&mut o);
    write_title(&mut o, "Power domains");
    for d in &pi.domains {
        write_domain(&mut o, d);
    }
    write_title(&mut o, "Logic ports");
    for p in &pi.ports {
        write_port(&mut o, p);
    }
    write_title(&mut o, "Power switches");
    for s in &pi.switches {
        write_power_switch(&mut o, s);
    }
    write_title(&mut o, "Isolations");
    for i in &pi.isolations {
        write_isolation(&mut o, i);
    }
    write_title(&mut o, "Level shifters");
    for l in &pi.level_shifters {
        write_level_shifter(&mut o, l);
    }
    o
}

fn write_header(o: &mut String) {
    o.push_str(HEADER);
    o.push('\n');
}

/// A blank line, then the title framed by `#` rules two wider than the title itself.
fn write_title(o: &mut String, title: &str) {
    let rule = "#".repeat(title.len() + 2);
    o.push('\n');
    o.push_str(&format!("{rule}\n# {title}\n{rule}\n"));
}

/// 🔑 **A top domain writes `-elements {.}` on the SAME line, without a continuation**, and its
/// stored elements are not written at all; any other domain writes its elements on a continued
/// line, and nothing when it has none.
fn write_domain(o: &mut String, d: &Domain) {
    o.push_str(&format!("create_power_domain {}", d.name));
    if d.top {
        o.push_str("  -elements {.}");
    } else if !d.elements.is_empty() {
        line_continue(o);
        o.push_str("  -elements {");
        write_list(o, &d.elements);
        o.push('}');
    }
    o.push('\n');
}

fn write_port(o: &mut String, p: &LogicPort) {
    o.push_str(&format!("create_logic_port {}", p.name));
    line_continue(o);
    o.push_str(&format!("  -direction {}", p.direction));
    o.push('\n');
}

/// Each optional part of a record is written only when present, and a LATER part only when the
/// one before it is: an on-state's expression needs its supply port, an ack's expression its net.
fn write_power_switch(o: &mut String, s: &PowerSwitch) {
    o.push_str(&format!("create_power_switch {}", s.name));
    if !s.output.0.is_empty() {
        line_continue(o);
        o.push_str("  -output_supply_port {");
        write_list(o, &present(&[&s.output.0, &s.output.1]));
        o.push('}');
    }
    for (port, net) in &s.inputs {
        line_continue(o);
        o.push_str("  -input_supply_port {");
        write_list(o, &present(&[port, net]));
        o.push('}');
    }
    for (port, net) in &s.controls {
        line_continue(o);
        o.push_str("  -control_port {");
        write_list(o, &present(&[port, net]));
        o.push('}');
    }
    for (state, port, expr) in &s.on_states {
        line_continue(o);
        o.push_str("  -on_state {");
        write_list(o, &present(&[state, port, expr]));
        o.push('}');
    }
    for (port, net, expr) in &s.acks {
        line_continue(o);
        o.push_str("  -ack_port {");
        write_list(o, &present(&[port, net, expr]));
        o.push('}');
    }
    line_continue(o);
    o.push_str(&format!("  -domain {{{}}}", s.domain));
    o.push('\n');
    write_power_switch_port_map(o, s);
}

/// The first item always, then each later one while the one before it was non-empty.
fn present(items: &[&String]) -> Vec<String> {
    let mut v = vec![items[0].clone()];
    for it in &items[1..] {
        if it.is_empty() {
            break;
        }
        v.push((*it).clone());
    }
    v
}

/// Nothing without a mapped cell. With one, the map is written even when it is empty (`{}`).
fn write_power_switch_port_map(o: &mut String, s: &PowerSwitch) {
    let Some(cell) = &s.lib_cell else { return };
    o.push_str(&format!("map_power_switch {}", s.name));
    line_continue(o);
    o.push_str(&format!("  -lib_cells {{{cell}}}"));
    line_continue(o);
    o.push_str("  -port_map {");
    for (k, (port, term)) in s.port_map.iter().enumerate() {
        if k > 0 {
            o.push(' ');
        }
        o.push('{');
        write_list(o, &[port.clone(), term.clone()]);
        o.push('}');
    }
    o.push('}');
    o.push('\n');
}

/// The sense is written only with a signal.
fn write_isolation(o: &mut String, i: &Isolation) {
    o.push_str(&format!("set_isolation {}", i.name));
    line_continue(o);
    o.push_str(&format!("  -domain {{{}}}", i.domain));
    if !i.applies_to.is_empty() {
        line_continue(o);
        o.push_str(&format!("  -applies_to {}", i.applies_to));
    }
    if !i.location.is_empty() {
        line_continue(o);
        o.push_str(&format!("  -location {}", i.location));
    }
    if !i.clamp_value.is_empty() {
        line_continue(o);
        o.push_str(&format!("  -clamp_value {}", i.clamp_value));
    }
    if !i.isolation_signal.is_empty() {
        line_continue(o);
        o.push_str(&format!("  -isolation_signal {{{}}}", i.isolation_signal));
        if !i.isolation_sense.is_empty() {
            line_continue(o);
            o.push_str(&format!("  -isolation_sense {}", i.isolation_sense));
        }
    }
    o.push('\n');
}

/// `-use_functional_equivalence` and `-threshold` are ALWAYS written; the threshold to three
/// decimals, rounded half to even on the stored `f32`'s exact value.
fn write_level_shifter(o: &mut String, l: &LevelShifter) {
    o.push_str(&format!("set_level_shifter {}", l.name));
    line_continue(o);
    o.push_str(&format!("  -domain {{{}}}", l.domain));
    if !l.elements.is_empty() {
        line_continue(o);
        o.push_str("  -elements {");
        write_list(o, &l.elements);
        o.push('}');
    }
    if !l.exclude_elements.is_empty() {
        line_continue(o);
        o.push_str("  -exclude_elements {");
        write_list(o, &l.exclude_elements);
        o.push('}');
    }
    let braced = [("source", &l.source), ("sink", &l.sink)];
    for (flag, v) in braced {
        if !v.is_empty() {
            line_continue(o);
            o.push_str(&format!("  -{flag} {{{v}}}"));
        }
    }
    line_continue(o);
    o.push_str("  -use_functional_equivalence ");
    o.push_str(if l.use_functional_equivalence { "TRUE" } else { "FALSE" });
    let bare = [("applies_to", &l.applies_to), ("applies_to_boundary", &l.applies_to_boundary), ("rule", &l.rule)];
    for (flag, v) in bare {
        if !v.is_empty() {
            line_continue(o);
            o.push_str(&format!("  -{flag} {v}"));
        }
    }
    line_continue(o);
    o.push_str(&format!("  -threshold {:.3}", l.threshold));
    if l.no_shift {
        line_continue(o);
        o.push_str("  -no_shift");
    }
    if l.force_shift {
        line_continue(o);
        o.push_str("  -force_shift");
    }
    if !l.location.is_empty() {
        line_continue(o);
        o.push_str(&format!("  -location {}", l.location));
    }
    let supplies = [
        ("input_supply", &l.input_supply),
        ("output_supply", &l.output_supply),
        ("internal_supply", &l.internal_supply),
        ("name_prefix", &l.name_prefix),
        ("name_suffix", &l.name_suffix),
    ];
    for (flag, v) in supplies {
        if !v.is_empty() {
            line_continue(o);
            o.push_str(&format!("  -{flag} {{{v}}}"));
        }
    }
    if !l.instances.is_empty() {
        line_continue(o);
        o.push_str("  -instance {");
        for (k, (inst, port)) in l.instances.iter().enumerate() {
            if k > 0 {
                o.push(' ');
            }
            o.push('{');
            write_list(o, &[inst.clone(), port.clone()]);
            o.push('}');
        }
        o.push('}');
    }
    o.push('\n');
}

/// 🔑 **One item is written BARE; two or more are each braced**, space separated. So
/// `-elements {u_aes_1}` but `-input_supply_port {{vin1} {vin2}}`.
fn write_list(o: &mut String, list: &[String]) {
    if list.len() == 1 {
        o.push_str(&list[0]);
        return;
    }
    let items: Vec<String> = list.iter().map(|i| format!("{{{i}}}")).collect();
    o.push_str(&items.join(" "));
}

fn line_continue(o: &mut String) {
    o.push_str(" \\\n");
}

#[cfg(test)]
mod tests {
    use super::*;

    fn s(v: &str) -> String {
        v.to_string()
    }

    #[test]
    fn every_section_banner_is_written_even_when_empty() {
        // Rule: the five banners always appear, each a blank line then the title framed by `#`
        // rules two wider than the title.
        let t = write_upf(&PowerIntent::default());
        let want = format!(
            "{HEADER}\n\n###############\n# Power domains\n###############\n\n#############\n# Logic ports\n#############\n\n################\n# Power switches\n################\n\n############\n# Isolations\n############\n\n################\n# Level shifters\n################\n"
        );
        assert_eq!(t, want);
    }

    #[test]
    fn a_top_domain_writes_dot_on_the_same_line_and_a_read_one_continues() {
        // Rule: `top` writes `  -elements {.}` with NO continuation and ignores its elements; a
        // domain that is not (yet) top writes its elements on a continued line, one bare.
        let mut o = String::new();
        write_domain(&mut o, &Domain { name: s("PD_TOP"), top: true, elements: vec![s("x")] });
        assert_eq!(o, "create_power_domain PD_TOP  -elements {.}\n");
        let mut o = String::new();
        write_domain(&mut o, &Domain { name: s("PD_TOP"), top: false, elements: vec![s(".")] });
        assert_eq!(o, "create_power_domain PD_TOP \\\n  -elements {.}\n");
        let mut o = String::new();
        write_domain(&mut o, &Domain { name: s("PD"), top: false, elements: vec![] });
        assert_eq!(o, "create_power_domain PD\n");
    }

    #[test]
    fn one_list_item_is_bare_and_several_are_each_braced() {
        let mut o = String::new();
        write_list(&mut o, &[s("a")]);
        assert_eq!(o, "a");
        let mut o = String::new();
        write_list(&mut o, &[s("a"), s("b")]);
        assert_eq!(o, "{a} {b}");
    }

    #[test]
    fn a_switch_record_stops_at_its_first_empty_part() {
        // Rule: an on-state's expression is written only with its supply port, even when the
        // expression itself is set.
        let sw = PowerSwitch {
            name: s("psw"),
            output: (s("vout"), s("")),
            inputs: vec![(s("vin1"), s("")), (s("vin2"), s("VDD"))],
            controls: vec![(s("sleep"), s("pd"))],
            on_states: vec![(s("ON"), s(""), s("!sleep"))],
            domain: s("PD"),
            ..Default::default()
        };
        let mut o = String::new();
        write_power_switch(&mut o, &sw);
        assert_eq!(
            o,
            "create_power_switch psw \\\n  -output_supply_port {vout} \\\n  -input_supply_port {vin1} \\\n  -input_supply_port {{vin2} {VDD}} \\\n  -control_port {{sleep} {pd}} \\\n  -on_state {ON} \\\n  -domain {PD}\n"
        );
    }

    #[test]
    fn a_port_map_needs_a_cell_and_is_written_even_when_empty() {
        let mut sw = PowerSwitch { name: s("psw"), domain: s("PD"), ..Default::default() };
        let mut o = String::new();
        write_power_switch_port_map(&mut o, &sw);
        assert_eq!(o, "");
        sw.lib_cell = Some(s("and2"));
        write_power_switch_port_map(&mut o, &sw);
        assert_eq!(o, "map_power_switch psw \\\n  -lib_cells {and2} \\\n  -port_map {}\n");
        sw.port_map = vec![(s("vin1"), s("A")), (s("vout"), s("X"))];
        let mut o = String::new();
        write_power_switch_port_map(&mut o, &sw);
        assert_eq!(o, "map_power_switch psw \\\n  -lib_cells {and2} \\\n  -port_map {{{vin1} {A}} {{vout} {X}}}\n");
    }

    #[test]
    fn an_isolation_sense_is_written_only_with_a_signal() {
        let iso = Isolation { name: s("iso"), domain: s("PD"), isolation_sense: s("low"), ..Default::default() };
        let mut o = String::new();
        write_isolation(&mut o, &iso);
        assert_eq!(o, "set_isolation iso \\\n  -domain {PD}\n");
        // And a signal without a sense writes the signal alone.
        let iso = Isolation { name: s("iso"), domain: s("PD"), isolation_signal: s("iso_n"), ..Default::default() };
        let mut o = String::new();
        write_isolation(&mut o, &iso);
        assert_eq!(o, "set_isolation iso \\\n  -domain {PD} \\\n  -isolation_signal {iso_n}\n");
    }

    #[test]
    fn a_threshold_rounds_half_to_even_on_the_stored_f32() {
        // Rule: three decimals of the f32's exact value; 0.0625 is an exact tie and goes DOWN to
        // the even digit, 0.1875 UP. 2.1 is stored as 2.0999999…, printed 2.100.
        for (v, want) in [(0.0625f32, "0.062"), (0.1875, "0.188"), (2.1, "2.100")] {
            let l = LevelShifter { name: s("ls"), domain: s("PD"), threshold: v, ..Default::default() };
            let mut o = String::new();
            write_level_shifter(&mut o, &l);
            assert!(o.contains(&format!("  -threshold {want}\n")), "{v}: {o}");
        }
    }

    #[test]
    fn a_level_shifter_writes_equivalence_and_threshold_always_and_the_rest_when_set() {
        let l = LevelShifter {
            name: s("ls_1"),
            domain: s("PD"),
            elements: vec![s("e1"), s("e2")],
            source: s("SRC"),
            use_functional_equivalence: true,
            rule: s("low_to_high"),
            threshold: 2.1,
            no_shift: true,
            input_supply: s("VDD"),
            instances: vec![(s("u1"), s("A"))],
            ..Default::default()
        };
        let mut o = String::new();
        write_level_shifter(&mut o, &l);
        assert_eq!(
            o,
            "set_level_shifter ls_1 \\\n  -domain {PD} \\\n  -elements {{e1} {e2}} \\\n  -source {SRC} \\\n  -use_functional_equivalence TRUE \\\n  -rule low_to_high \\\n  -threshold 2.100 \\\n  -no_shift \\\n  -input_supply {VDD} \\\n  -instance {{{u1} {A}}}\n"
        );
    }
}

